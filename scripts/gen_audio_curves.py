"""Generate the TypeScript mirror of the audio curve registry (astrid/core/timeline/audio_curves.json).

The pinned v0.0.6 reference snapshot stays byte-identical to upstream; the renderer package
consumes this mirror when it integrates fade curves."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "astrid/core/timeline/audio_curves.json"
TARGET = ROOT / "astrid/core/timeline/audio_curves.generated.ts"


def render() -> str:
    curves = json.loads(SOURCE.read_text(encoding="utf-8"))["curves"]
    return "// Generated by scripts/gen_audio_curves.py; edit audio_curves.json.\n" + (
        "export const AUDIO_GAIN_CURVES = "
        + json.dumps(curves, indent=2, sort_keys=True)
        + " as const;\n"
    )


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8")
