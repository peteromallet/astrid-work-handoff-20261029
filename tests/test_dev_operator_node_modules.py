def _wire_promote(monkeypatch: pytest.MonkeyPatch, tmp_path: Path, events: list[tuple[Any, ...]]) -> Path:
    serve = tmp_path / "served"
    (serve / "remotion").mkdir(parents=True)
    runtime = tmp_path / "runtime"
    runtime.mkdir()
    (runtime / "generic-host.json").write_text(json.dumps({"process_birth_id": "b", "runtime_instance_id": "i"}), encoding="utf-8")
    state = {"process_birth_id": "b", "runtime_instance_id": "i"}
    reopened = {"done": False}
    monkeypatch.setattr(dev, "_reopened", reopened, raising=False)
    monkeypatch.setattr(dev, "served_profile", lambda _: {"source_checkout": str(serve)})
    monkeypatch.setattr(dev, "_require_linked_serve_worktree", lambda *_: None)
    monkeypatch.setattr(dev, "in_flight_tasks", lambda _: [])

    def git(root, *args):
        if args[0] == "status":
            return ""
        if args[0] == "checkout":
            events.append(("checkout", args[-1]))
            return ""
        return "new" if args[0] == "rev-parse" and root != serve else "old"

    monkeypatch.setattr(dev, "_git", git)
    monkeypatch.setattr(dev, "host_state", lambda _: {"ready": True, "pid": 9, "source_checkout_digest": "d",
                                                      "source_closure_digest": "c", "recorded": True})
    monkeypatch.setattr(dev, "pair_report", lambda **_: {"status": "paired", "reason": "ok"})
    monkeypatch.setattr(
        dev, "_read_json",
        lambda path: ({**state, "process_birth_id": "b2"} if reopened["done"] else dict(state)) if path.name == "generic-host.json" else None)
    return serve


def test_promote_syncs_node_modules_and_sweeps_orphans_after_checkout_before_reopen(tmp_path, monkeypatch) -> None:
    events: list[tuple[Any, ...]] = []
    serve = _wire_promote(monkeypatch, tmp_path, events)

    class Client:
        def __call__(self, *, start_pack_host):
            events.append(("open", start_pack_host))
            if start_pack_host:
                dev._reopened["done"] = True
            return nullcontext(None)

    payload = dev.run_promote(
        data_root=tmp_path, client=tmp_path / "source", open_client=Client(),
        terminate_host=lambda state: events.append(("terminate",)),
        sync_node_modules=lambda path: events.append(("sync", path)) or {"synced": False, "reason": "in sync", "lockfile": "abc"},
        reap_orphans=lambda checkouts: events.append(("reap", checkouts)) or [{"pid": 7, "command": "x"}],
        digest_fn=lambda _: "d", closure_fn=lambda _: "c", ready_wait_seconds=0.1)

    names = [event[0] for event in events]
    assert names == ["open", "terminate", "checkout", "reap", "sync", "open"], names
    assert ("sync", serve / "remotion") in events
    assert payload["node_modules"]["reason"] == "in sync" and payload["orphans_reaped"] == [{"pid": 7, "command": "x"}]


def test_promote_reports_a_failed_node_modules_sync_with_the_rerun_command(tmp_path, monkeypatch) -> None:
    events: list[tuple[Any, ...]] = []
    _wire_promote(monkeypatch, tmp_path, events)

    def sync(path):
        raise DevOperatorError("npm ci failed in /x: fatal: reconnect failed", state="error", next_action="rerun npm ci by hand")

    with pytest.raises(DevOperatorError, match="already at") as raised:
        dev.run_promote(data_root=tmp_path, client=tmp_path / "source", open_client=lambda **_: nullcontext(None),
                        terminate_host=lambda state: None, sync_node_modules=sync,
                        digest_fn=lambda _: "d", closure_fn=lambda _: "c", ready_wait_seconds=0.1)
    assert raised.value.state == "error"
    assert "dev promote --ref" in (raised.value.next_action or "")
