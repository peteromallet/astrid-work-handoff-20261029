"""Restored from f840ec1c (lost in the combined port): remotion node_modules sync inside ``dev promote``.

``sync_remotion_node_modules`` brings ``remotion/node_modules`` in line with the lockfile
(``npm ci`` under the pinned Node) and keeps the Remotion Chrome. The helper tests run with a
fake npm; the promote wiring test runs against the owner-bound promote of the combined port.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
from contextlib import nullcontext
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

from astrid.core.gateway import dev_operator as dev
from astrid.core.gateway.dev_operator import DevOperatorError, render_human, sync_remotion_node_modules


class FakeNpm:
    """Stands in for ``npm ci``: records each call and returns a canned result. The real npm never runs."""

    def __init__(self, returncode: int = 0, stderr: str = "") -> None:
        self.returncode = returncode
        self.stderr = stderr
        self.calls: list[tuple[list[str], Path, dict[str, str]]] = []

    def __call__(self, cmd: list[str], cwd: Path, env: dict[str, str]) -> subprocess.CompletedProcess:
        self.calls.append((list(cmd), Path(cwd), dict(env)))
        return subprocess.CompletedProcess(cmd, self.returncode, "", self.stderr)


def _resolver(bin_dir: Path):
    return lambda project: SimpleNamespace(ok=True, path=bin_dir / "node", problem=None)


def _remotion(tmp_path: Path) -> Path:
    project = tmp_path / "remotion"
    project.mkdir()
    (project / "package-lock.json").write_text(json.dumps({
        "name": "tools-remotion", "lockfileVersion": 3,
        "packages": {"": {"name": "tools-remotion"}, "node_modules/a": {"version": "1.0.0"}},
    }), encoding="utf-8")
    return project


def _lock_digest(project: Path) -> str:
    return hashlib.sha256((project / "package-lock.json").read_bytes()).hexdigest()


def _stamp(project: Path) -> Path:
    return project / "node_modules" / ".astrid-lockfile.sha256"


def test_node_modules_in_sync_by_stamp_runs_nothing(tmp_path: Path) -> None:
    project = _remotion(tmp_path)
    digest = _lock_digest(project)
    _stamp(project).parent.mkdir()
    _stamp(project).write_text(digest + "\n", encoding="utf-8")
    npm = FakeNpm()
    result = sync_remotion_node_modules(project, run=npm, resolve_node=_resolver(tmp_path / "bin"))
    assert result == {"synced": False, "reason": "in sync", "lockfile": digest[:12]}
    assert npm.calls == []
    assert _stamp(project).read_text(encoding="utf-8") == digest + "\n"


def test_first_run_with_matching_hidden_lockfile_writes_stamp_without_npm(tmp_path: Path) -> None:
    project = _remotion(tmp_path)
    digest = _lock_digest(project)
    (project / "node_modules").mkdir()
    (project / "node_modules" / ".package-lock.json").write_text(json.dumps({
        "lockfileVersion": 3, "packages": {"node_modules/a": {"version": "1.0.0"}},
    }), encoding="utf-8")
    npm = FakeNpm()
    result = sync_remotion_node_modules(project, run=npm, resolve_node=_resolver(tmp_path / "bin"))
    assert result == {"synced": False, "reason": "in sync", "lockfile": digest[:12]}
    assert npm.calls == []
    assert _stamp(project).read_text(encoding="utf-8").strip() == digest


def test_first_run_with_different_hidden_lockfile_runs_npm_ci(tmp_path: Path) -> None:
    project = _remotion(tmp_path)
    (project / "node_modules").mkdir()
    (project / "node_modules" / ".package-lock.json").write_text(json.dumps({
        "packages": {"node_modules/a": {"version": "0.9.0"}},
    }), encoding="utf-8")
    npm = FakeNpm()
    result = sync_remotion_node_modules(project, run=npm, resolve_node=_resolver(tmp_path / "bin"))
    assert result["synced"] is True and result["lockfile_before"] is None
    assert len(npm.calls) == 1


def test_changed_lockfile_runs_npm_ci_under_pinned_node(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    project = _remotion(tmp_path)
    (project / "node_modules").mkdir()
    _stamp(project).write_text("ab" * 32 + "\n", encoding="utf-8")
    bin_dir = tmp_path / "tools" / "node-v20.19.4-darwin-arm64" / "bin"
    monkeypatch.setenv("PATH", "/usr/bin:/bin")
    npm = FakeNpm()
    result = sync_remotion_node_modules(project, run=npm, resolve_node=_resolver(bin_dir))
    digest = _lock_digest(project)
    assert len(npm.calls) == 1
    cmd, cwd, env = npm.calls[0]
    assert cmd == [str(bin_dir / "npm"), "ci"]
    assert cwd == project
    assert env["PATH"] == f"{bin_dir}{os.pathsep}/usr/bin:/bin"
    assert result["synced"] is True and result["command"] == "npm ci"
    assert result["lockfile_before"] == "ab" * 6
    assert result["lockfile"] == digest[:12]
    assert isinstance(result["seconds"], float)
    assert _stamp(project).read_text(encoding="utf-8").strip() == digest


def test_npm_ci_failure_raises_with_stderr_tail(tmp_path: Path) -> None:
    project = _remotion(tmp_path)
    (project / "node_modules").mkdir()
    _stamp(project).write_text("ab" * 32 + "\n", encoding="utf-8")
    npm = FakeNpm(returncode=1, stderr="npm error code ECONNRESET\nnpm error network aborted\n"
                                       "npm error fatal: reconnect failed\n")
    with pytest.raises(DevOperatorError, match="npm ci failed in .*reconnect failed") as raised:
        sync_remotion_node_modules(project, run=npm, resolve_node=_resolver(tmp_path / "bin"))
    assert raised.value.state == "error"
    assert "npm ci" in (raised.value.next_action or "")
    assert _stamp(project).read_text(encoding="utf-8").strip() == "ab" * 32  # a failed install leaves no new stamp


def test_no_pinned_node_refuses_before_npm_runs(tmp_path: Path) -> None:
    project = _remotion(tmp_path)
    npm = FakeNpm()
    resolve = lambda path: SimpleNamespace(ok=False, path=None, problem="no Node v20.19.4 found")
